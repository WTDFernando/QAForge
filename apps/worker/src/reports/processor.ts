import { randomUUID } from 'node:crypto';
import type { Job } from 'bullmq';
import { createStorage, getPrisma, type Prisma } from '@qaforge/db';
import { buildReport, EXPORT_CONTENT_TYPES, exportFileName, renderExport } from '@qaforge/reports';
import { nextCronRun } from '@qaforge/runner';
import {
  EXPORT_FORMATS,
  REPORT_TYPE_INFO,
  VERDICT_LABEL,
  type ReportDoc,
  type ReportJob,
  type ReportNarrative,
  type ReportParams,
  type ReportType,
} from '@qaforge/shared';
import { logger } from '../logger';
import { createMailer, type SendMail } from './mailer';

const prisma = () => getPrisma();
const json = (v: unknown) => v as Prisma.InputJsonValue;
const DAY = 86_400_000;

export interface ReportDeps {
  /** Queue the Report Agent; resolves true when a narrative job was started. */
  requestNarrative?: (reportId: string) => Promise<boolean>;
  sendMail?: SendMail | null;
  now?: () => Date;
}

/** Stored params carry the dates as ISO strings. */
function parseParams(raw: unknown): ReportParams & { narrative?: boolean } {
  const p = (raw ?? {}) as Record<string, unknown>;
  return {
    releaseId: typeof p.releaseId === 'string' ? p.releaseId : undefined,
    testRunIds: Array.isArray(p.testRunIds) ? (p.testRunIds as string[]) : undefined,
    from: typeof p.from === 'string' ? new Date(p.from) : undefined,
    to: typeof p.to === 'string' ? new Date(p.to) : undefined,
    narrative: p.narrative === true,
  };
}

/** Build the numbers, then the exports. The AI narrative (if asked for) arrives later and re-exports. */
export async function generateReport(reportId: string, deps: ReportDeps = {}) {
  const db = prisma();
  const report = await db.report.findUniqueOrThrow({ where: { id: reportId } });
  const params = parseParams(report.params);
  let doc: ReportDoc;
  try {
    doc = await buildReport(report.type as ReportType, {
      db,
      projectId: report.projectId,
      params,
      now: deps.now?.(),
    });
  } catch (e) {
    await db.report.update({
      where: { id: reportId },
      data: { status: 'FAILED', error: (e as Error).message.slice(0, 2000) },
    });
    throw e;
  }
  await db.report.update({
    where: { id: reportId },
    data: { status: 'READY', error: null, data: json(doc) },
  });
  const narrating =
    params.narrative && deps.requestNarrative ? await deps.requestNarrative(reportId) : false;
  await exportReport(reportId, deps);
  return { doc, narrating };
}

/** Render every format and store them as the report's attachments (replacing older exports). */
export async function exportReport(reportId: string, deps: ReportDeps = {}) {
  const db = prisma();
  const report = await db.report.findUniqueOrThrow({
    where: { id: reportId },
    include: {
      project: {
        select: {
          organizationId: true,
          createdById: true,
          key: true,
          organization: { select: { slug: true } },
        },
      },
      schedule: true,
    },
  });
  if (!report.data) return [];
  const doc = report.data as unknown as ReportDoc;
  const narrative = (report.narrative ?? null) as ReportNarrative | null;
  const storage = createStorage();
  const old = await db.attachment.findMany({ where: { entityType: 'report', entityId: reportId } });
  const firstExport = old.length === 0;
  const files: { filename: string; content: Buffer; contentType: string; format: string }[] = [];
  for (const format of EXPORT_FORMATS) {
    const content = await renderExport(format, doc, narrative);
    const id = randomUUID();
    const fileName = exportFileName(doc, format);
    const key = `${report.project.organizationId}/${report.projectId}/reports/${id}/${fileName}`;
    await storage.put(key, content, EXPORT_CONTENT_TYPES[format]);
    await db.attachment.create({
      data: {
        id,
        projectId: report.projectId,
        storageKey: key,
        fileName,
        contentType: EXPORT_CONTENT_TYPES[format],
        size: content.length,
        entityType: 'report',
        entityId: reportId,
        // Generated by us from database values: nothing to scan.
        scanStatus: 'SKIPPED',
        createdById: report.createdById ?? report.project.createdById,
      },
    });
    files.push({ filename: fileName, content, contentType: EXPORT_CONTENT_TYPES[format], format });
  }
  for (const a of old) {
    await storage.delete(a.storageKey).catch(() => undefined);
    await db.attachment.delete({ where: { id: a.id } }).catch(() => undefined);
  }
  if (report.schedule && firstExport) await emailReport(report, doc, files, deps);
  return files.map((f) => f.filename);
}

async function emailReport(
  report: {
    id: string;
    schedule: { name: string; recipients: string[]; formats: string[] } | null;
    project: { key: string; organization: { slug: string } };
  },
  doc: ReportDoc,
  files: { filename: string; content: Buffer; contentType: string; format: string }[],
  deps: ReportDeps,
) {
  const send = deps.sendMail === undefined ? createMailer() : deps.sendMail;
  const s = report.schedule!;
  if (!send) {
    logger.warn({ reportId: report.id }, 'scheduled report not emailed: SMTP_URL is not set');
    return;
  }
  const url = process.env.PUBLIC_APP_URL ?? process.env.WEB_URL;
  const link = url
    ? `${url}/${report.project.organization.slug}/p/${report.project.key}/reports/${report.id}`
    : null;
  const kpis = doc.kpis.map((k) => `${k.label}: ${k.value}${k.unit ?? ''}`);
  const verdict = doc.verdict ? `${VERDICT_LABEL[doc.verdict.value]}: ${doc.verdict.reason}` : null;
  const esc = (t: string) =>
    t.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
  await send({
    to: s.recipients,
    subject: `${doc.title}: ${doc.project.name} · ${doc.subtitle}`,
    text: [
      `${s.name} (${doc.project.name})`,
      verdict,
      '',
      ...kpis,
      '',
      link ? `Open in QAForge: ${link}` : '',
    ]
      .filter((l) => l !== null)
      .join('\n'),
    html: `<p><strong>${esc(s.name)}</strong> · ${esc(doc.project.name)}</p>${verdict ? `<p>${esc(verdict)}</p>` : ''}<ul>${kpis.map((k) => `<li>${esc(k)}</li>`).join('')}</ul>${link ? `<p><a href="${esc(link)}">Open in QAForge</a></p>` : ''}`,
    attachments: files
      .filter((f) => s.formats.includes(f.format))
      .map(({ filename, content, contentType }) => ({ filename, content, contentType })),
  });
  logger.info({ reportId: report.id, recipients: s.recipients.length }, 'scheduled report emailed');
}

/** Start reports for schedules that are due; each schedule is claimed atomically. */
export async function reportScheduleTick(
  enqueue: (reportId: string) => Promise<unknown>,
  now = new Date(),
) {
  const db = prisma();
  const due = await db.reportSchedule.findMany({
    where: { enabled: true, nextRunAt: { lte: now } },
    take: 100,
  });
  const started: string[] = [];
  for (const s of due) {
    const id = await db.$transaction(async (tx) => {
      const claimed = await tx.reportSchedule.updateMany({
        where: { id: s.id, nextRunAt: s.nextRunAt },
        data: { lastRunAt: now, nextRunAt: nextCronRun(s.cron, s.timezone, now) },
      });
      if (!claimed.count) return null;
      // Period reports cover the time since the previous run (first run: the last 7 days).
      const from = s.lastRunAt ?? new Date(now.getTime() - 7 * DAY);
      const params = { ...(s.params as object), from: from.toISOString(), to: now.toISOString() };
      const r = await tx.report.create({
        data: {
          projectId: s.projectId,
          scheduleId: s.id,
          type: s.type,
          title: s.name,
          params: json(params),
          createdById: s.createdById,
        },
      });
      return r.id;
    });
    if (id) {
      await enqueue(id);
      started.push(id);
    }
  }
  return started;
}

export function createReportProcessor(
  enqueue: (job: ReportJob) => Promise<unknown>,
  deps: ReportDeps = {},
) {
  return async (job: Job<ReportJob>) => {
    if (job.data.kind === 'tick')
      return {
        started: await reportScheduleTick((reportId) => enqueue({ kind: 'generate', reportId })),
      };
    if (job.data.kind === 'export') return { files: await exportReport(job.data.reportId!, deps) };
    const r = await generateReport(job.data.reportId!, deps);
    return { type: r.doc.type, narrating: r.narrating, title: REPORT_TYPE_INFO[r.doc.type].label };
  };
}
